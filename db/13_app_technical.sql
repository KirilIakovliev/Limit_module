-- ============================================================================
-- APPLICATION TECHNICAL TABLES — таблицы, принадлежащие Лимитному модулю.
-- НЕ являются копией DataHub, поэтому ограничения здесь допустимы.
--
-- app.load_log — журнал загрузок копии витрин.
-- Обоснование: БТ 2.2 / 2.5.3 требуют показывать дату и время последнего
-- обновления данных и предупреждать, если обновления не было > 24 ч. Ни одна из
-- 13 таблиц-копий не содержит метки времени загрузки. Читается endpoint'ом
-- GET /api/meta. Одна строка на загрузку одной таблицы (или на загрузку в целом
-- с table_name = '*').
-- На TEST строку вставляет db/91_test_marts.sql; на PROD её пишет механизм
-- передачи из DataHub (контракт не определён — см. docs/database_migration.md).
-- ============================================================================

CREATE TABLE IF NOT EXISTS app.load_log (
	id          BIGSERIAL PRIMARY KEY,
	table_name  TEXT NOT NULL,                       -- имя загруженной таблицы или '*'
	loaded_at   TIMESTAMPTZ NOT NULL DEFAULT now(),  -- момент завершения загрузки копии
	data_date   DATE,                                -- отчётная дата данных (T-1), если известна
	row_count   BIGINT,                              -- число строк после загрузки, если известно
	note        TEXT                                 -- произвольный комментарий загрузчика
);
