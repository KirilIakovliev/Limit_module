L3_RANDOM = demo("random() внутри LATERAL", r"""
Задача: выдать каждому продукту компании свою случайную сумму.

```sql
CREATE TABLE demo_companies (id int, name text);
INSERT INTO demo_companies VALUES (1, 'Магнит'), (2, 'Северсталь');

SELECT c.name, p.product, round(a.amt) AS сумма
FROM demo_companies c
CROSS JOIN LATERAL (VALUES ('Овердрафт'), ('Гарантии'), ('Аккредитив')) AS p(product)
CROSS JOIN LATERAL (SELECT random() * 1000 AS amt) AS a;
```

```
    name    |  product   | сумма
------------+------------+-------
 Магнит     | Овердрафт  |   183
 Магнит     | Гарантии   |   183
 Магнит     | Аккредитив |   183
 Северсталь | Овердрафт  |   183
 Северсталь | Гарантии   |   183
 Северсталь | Аккредитив |   183
```

Одно значение на все шесть строк. План объясняет почему:

```
 Nested Loop
   ->  Seq Scan on demo_companies c
   ->  Materialize            ← результат посчитан один раз и переиспользован
         ->  Nested Loop
               ->  Result
```

**`Materialize`** — «вычислить и запомнить». Подзапрос
`(SELECT random() * 1000)` не ссылается ни на один внешний столбец, значит
с точки зрения планировщика его результат не может отличаться между строками.
Оптимизация законная — просто `random()` нарушает предположение, на котором
она построена.

**Починка 1 — считать в списке выборки:**

```sql
SELECT c.name, p.product, round(random() * 1000) AS сумма
FROM demo_companies c
CROSS JOIN LATERAL (VALUES ('Овердрафт'), ('Гарантии'), ('Аккредитив')) AS p(product);
```

```
 Магнит     | Овердрафт  |   284
 Магнит     | Гарантии   |   620      ← все значения разные
 Магнит     | Аккредитив |   769
 Северсталь | Овердрафт  |   814
```

**Починка 2 — сделать подзапрос зависимым от внешнего столбца:**

```sql
CROSS JOIN LATERAL (SELECT random() * 1000 + c.id * 0 AS amt) AS a
```

```
 Магнит     | Овердрафт  |   959
 Магнит     | Гарантии   |   959      ← пересчитан на каждую компанию,
 Магнит     | Аккредитив |   959         но один на её продукты
 Северсталь | Овердрафт  |    56
```

Разница между починками видна сразу: второй вариант даёт значение на
**компанию**, а не на строку, потому что зависит от `c.id`, а не от
`p.product`. Именно в такой форме баг и жил в проекте.

**Общий принцип.** SQL декларативен: вы описываете *что* получить, а *как* и
*сколько раз* считать — решает планировщик. Пока функции чистые (одинаковый
вход → одинаковый выход), это незаметно. `random()`, `now()`, `nextval()`
чистыми не являются, и с ними порядок вычислений становится виден.
""")

L3_IDEMPOTENT = demo("идемпотентность миграции", r"""
**Как ломается обычная миграция.** Файл выполнен три раза подряд:

```sql
CREATE TABLE IF NOT EXISTS demo_bad (id serial PRIMARY KEY, name text);
INSERT INTO demo_bad (name) VALUES ('ГК «Цветы»');
```

```
 id |    name
----+------------
  1 | ГК «Цветы»
  2 | ГК «Цветы»     ← дубль
  3 | ГК «Цветы»     ← ещё дубль
```

А добавление колонки со второго раза просто падает:

```sql
ALTER TABLE demo_companies ADD COLUMN kpp text;
```

```
ALTER TABLE                                             ← первый запуск
ERROR: column "kpp" of relation "demo_companies" already exists   ← второй
```

**Те же операции в идемпотентном виде:**

```sql
CREATE TABLE IF NOT EXISTS demo_groups (id serial PRIMARY KEY, name text UNIQUE);
ALTER TABLE demo_companies ADD COLUMN IF NOT EXISTS ogrn text;
INSERT INTO demo_groups (name) VALUES ('ГК «Цветы»') ON CONFLICT (name) DO NOTHING;
UPDATE demo_companies SET ogrn = COALESCE(ogrn, '1' || lpad(id::text, 12, '0'));
```

Три запуска подряд:

```
--- запуск 1: 1 строк в demo_groups
--- запуск 2: 1 строк в demo_groups
--- запуск 3: 1 строк в demo_groups

 id |    name    |     ogrn
----+------------+---------------
  1 | Магнит     | 1000000000001
  2 | Северсталь | 1000000000002
```

**Что делает каждая конструкция:**

| Конструкция | Поведение при повторе |
|---|---|
| `CREATE TABLE IF NOT EXISTS` | таблица есть — пропустить |
| `ADD COLUMN IF NOT EXISTS` | колонка есть — пропустить |
| `ON CONFLICT (name) DO NOTHING` | такая запись есть — не вставлять |
| `COALESCE(ogrn, ...)` | значение уже стоит — не перезаписывать |

**Зачем нам это было нужно.** Обычно применение миграций отслеживают: ведут
таблицу «какие файлы накатаны» и инструмент вроде Alembic. Раз наши миграции
безвредны при повторе, учёт не нужен вовсе — они выполняются **при каждом
старте API** (`api/app/main.py:55`, функция `ensure_schema`).

Это решило конкретную проблему: файлы из `db/` Postgres выполняет только при
создании пустого тома. База уже работала, `03_search_index.sql` молча
игнорировался, приложение падало с `column "search_name" does not exist`.
Теперь достаточно перезапустить API.

**Цена подхода:** миграции должны оставаться дешёвыми, потому что выполняются
на каждом старте. `CREATE INDEX` на большой таблице так запускать нельзя —
для таких случаев нужен нормальный инструмент миграций.
""")

