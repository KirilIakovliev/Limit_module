def main() -> int:
    for filename, anchor, block, mode in INSERTS:
        path = COURSE / filename
        text = path.read_text(encoding="utf-8")

        if block.strip() in text:
            print(f"уже на месте: {filename} / {anchor[:40]}")
            continue
        if anchor not in text:
            print(f"ЯКОРЬ НЕ НАЙДЕН: {filename} / {anchor[:40]}")
            continue

        if mode == "before":
            text = text.replace(anchor, block + "\n" + anchor, 1)
        else:  # after-section: вставить перед следующим заголовком того же уровня
            start = text.index(anchor)
            nxt = text.find("\n## ", start + len(anchor))
            nxt = nxt if nxt > -1 else len(text)
            text = text[:nxt] + "\n" + block + text[nxt:]

        path.write_text(text, encoding="utf-8")
        print(f"вставлено: {filename} / {anchor[:40]}")
    return 0


